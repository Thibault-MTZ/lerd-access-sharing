const fixtures=[
 {project:'Alpha',kind:'site',branch:'',visibility:'closed',paused:false,access_policy_reported:true,access_summary:{mode:'closed',revision:2}},
 {project:'Alpha',kind:'worktree',branch:'agent-v3',git_branch:'agent/v3',visibility:'public',paused:false,access_policy_reported:true,access_summary:{mode:'ip',revision:3}},
 {project:'Alpha',kind:'worktree',branch:'docs-update',git_branch:'docs/update',visibility:'closed',paused:false,access_policy_reported:true,access_summary:{mode:'closed',revision:1}},
 {project:'Beta',kind:'site',branch:'',visibility:'private',paused:false,access_policy_reported:false},
 {project:'Gamma',kind:'site',branch:'',visibility:'public',paused:true,access_policy_reported:true,access_summary:{mode:'password',revision:4}}
];
assert.equal(nonEmptySecret('x'),true);
assert.equal(nonEmptySecret('é'.repeat(80)),true);
assert.equal(nonEmptySecret('  '),true);
assert.equal(nonEmptySecret(''),false);
const grouped=groupShares(fixtures);
assert.equal(grouped.length,3);
assert.equal(grouped.find(group=>group.project==='Alpha').worktrees.length,2);
const branchMatch=filterGroups(grouped,{query:'agent/v3',share:'public',protection:'ip',nativeAccessAvailable:true});
assert.equal(branchMatch.length,1);
assert.equal(branchMatch[0].project,'Alpha');
assert.equal(branchMatch[0].site,null);
assert.deepEqual(branchMatch[0].worktrees.map(row=>row.branch),['agent-v3']);
const projectMatch=filterGroups(grouped,{query:'Alpha',nativeAccessAvailable:true});
assert.ok(projectMatch[0].site);
assert.equal(projectMatch[0].worktrees.length,2);
const contextual=filterGroups(grouped,{site:'Alpha',branch:'agent-v3',share:'all',nativeAccessAvailable:true});
assert.equal(contextual.length,1);
assert.equal(contextual[0].site,null);
assert.deepEqual(contextual[0].worktrees.map(row=>row.branch),['agent-v3']);
const ipOnly=filterGroups(grouped,{protection:'ip',nativeAccessAvailable:true});
assert.deepEqual(ipOnly.flatMap(group=>group.worktrees).map(row=>row.git_branch),['agent/v3']);
const stopped=filterGroups(grouped,{share:'stopped',nativeAccessAvailable:true});
assert.equal(stopped.flatMap(group=>[group.site,...group.worktrees].filter(Boolean)).length,2);
assert.deepEqual(sortGroups(grouped,'name').map(group=>group.project),['Alpha','Beta','Gamma']);
assert.deepEqual(sortGroups(grouped,'activity').map(group=>group.project),['Alpha','Beta','Gamma']);
assert.deepEqual(sortGroups(grouped,'protection').map(group=>group.project),['Alpha','Gamma','Beta']);
assert.deepEqual(sortGroups(grouped.find(group=>group.project==='Alpha').worktrees.map(row=>({project:row.project,site:null,worktrees:[row]})),'protection').flatMap(group=>group.worktrees).map(row=>row.branch),['docs-update','agent-v3']);
